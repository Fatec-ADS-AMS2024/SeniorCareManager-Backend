using SeniorCareManager.WebAPI.Objects.Contracts.Exceptions;
using SeniorCareManager.WebAPI.Objects.Dtos.DataAnnotations.Base;
using SeniorCareManager.WebAPI.Services.Utils;
using System.ComponentModel.DataAnnotations;
using System.Linq;

namespace SeniorCareManager.WebAPI.Objects.Dtos.DataAnnotations.Valid
{
    public class CpfCnpjValidator : BaseAnnotation
    {
        private readonly ValidationType _type = ValidationType.CpfCnpj;

        public CpfCnpjValidator(ValidationType type = ValidationType.CpfCnpj)
        {
            _type = type;
        }

        public override FieldError? Execute()
        {
            if (Value.IsNull())
                return null;

            var text = Value as string;

            var digitsOnly = new string(text?.Where(char.IsDigit).ToArray());

            bool isValid = false;
            if (_type == ValidationType.Cpf)
            {
                isValid = IsCpf(digitsOnly);
            }
            else if (_type == ValidationType.Cnpj)
            {
                isValid = IsCnpj(digitsOnly);
            }
            else
            {
                isValid = IsCpf(digitsOnly) || IsCnpj(digitsOnly);
            }

            return isValid ? null : ReturnError(NameProperty, "CPF/CNPJ inválido.");
        }

        private static bool IsCpf(string cpf)
        {
            int[] multiplicador1 = new int[9] { 10, 9, 8, 7, 6, 5, 4, 3, 2 };
            int[] multiplicador2 = new int[10] { 11, 10, 9, 8, 7, 6, 5, 4, 3, 2 };
            string tempCpf;
            string digito;
            int soma;
            int resto;
            if (cpf.Length != 11 || new string(cpf[0], 11) == cpf)
                return false;
            tempCpf = cpf.Substring(0, 9);
            soma = 0;

            for (int i = 0; i < 9; i++)
                soma += int.Parse(tempCpf[i].ToString()) * multiplicador1[i];
            resto = soma % 11;
            if (resto < 2)
                resto = 0;
            else
                resto = 11 - resto;
            digito = resto.ToString();
            tempCpf = tempCpf + digito;
            soma = 0;
            for (int i = 0; i < 10; i++)
                soma += int.Parse(tempCpf[i].ToString()) * multiplicador2[i];
            resto = soma % 11;
            if (resto < 2)
                resto = 0;
            else
                resto = 11 - resto;
            digito = digito + resto.ToString();
            return cpf.EndsWith(digito);
        }

        private static bool IsCnpj(string cnpj)
        {
            int[] multiplicador1 = new int[12] { 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2 };
            int[] multiplicador2 = new int[13] { 6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2 };
            int soma;
            int resto;
            string digito;
            string tempCnpj;
            if (cnpj.Length != 14 || new string(cnpj[0], 14) == cnpj)
                return false;
            tempCnpj = cnpj.Substring(0, 12);
            soma = 0;
            for (int i = 0; i < 12; i++)
                soma += int.Parse(tempCnpj[i].ToString()) * multiplicador1[i];
            resto = (soma % 11);
            if (resto < 2)
                resto = 0;
            else
                resto = 11 - resto;
            digito = resto.ToString();
            tempCnpj = tempCnpj + digito;
            soma = 0;
            for (int i = 0; i < 13; i++)
                soma += int.Parse(tempCnpj[i].ToString()) * multiplicador2[i];
            resto = (soma % 11);
            if (resto < 2)
                resto = 0;
            else
                resto = 11 - resto;
            digito = digito + resto.ToString();
            return cnpj.EndsWith(digito);
        }

    }
}
